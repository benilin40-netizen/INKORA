export type Genre = 
  | 'Romance'
  | 'Fantasy'
  | 'Mystery'
  | 'Adventure'
  | 'Thriller'
  | 'Mystery & Thriller'
  | 'Science Fiction'
  | 'Drama'
  | 'Horror'
  | 'Poetry'
  | 'Short Stories'
  | 'Historical Fiction' 
  | 'Literary Fiction' 
  | 'Cyberpunk';

export interface Chapter {
  id: string;
  title: string;
  content: string;
  wordCount: number;
  order: number;
  lastModified: number;
}

export interface Character {
  id: string;
  name: string;
  role: 'Protagonist' | 'Antagonist' | 'Supporting' | 'Minor';
  description: string;
  arc: string;
}

export interface StoryOutline {
  premise: string;
  acts: string[];
  notes: string;
}

export interface CoverConfig {
  title: string;
  author: string;
  subtitle?: string;
  tagline?: string;
  genre?: Genre | string;
  showGenre?: boolean;
  bgColor: string;
  bgGradient: string;
  bgType?: 'gradient' | 'color' | 'image';
  bgImage?: string; // Data URL or verified image URL
  overlayPattern: 'none' | 'dots' | 'grid' | 'vignette' | 'stars';
  overlayOpacity?: number; // 0 to 1
  overlayColor?: string; // hex or rgba
  fontFamily: 'serif' | 'sans' | 'mono' | 'display';
  fontStyle?: 'normal' | 'italic';
  fontWeight?: 'normal' | 'medium' | 'bold';
  textAlign?: 'left' | 'center' | 'right';
  titleColor: string;
  subtitleColor?: string;
  authorColor: string;
  titleSize: number; // in rem
  subtitleSize?: number; // in rem
  titlePosition: { x: number; y: number };
  authorPosition: { x: number; y: number };
  badgeText?: string;
  artworkStyle?: string;
  exportedCoverDataUrl?: string; // high-res cached rendering for cards
}

export interface Story {
  id: string;
  userId: string;
  authorName: string;
  title: string;
  synopsis: string;
  genre?: Genre | string;
  tags: string[];
  status: 'draft' | 'published';
  visibility: 'private' | 'public';
  chapters: Chapter[];
  characters: Character[];
  outline: StoryOutline;
  cover: CoverConfig;
  createdAt: number;
  updatedAt: number;
  totalWordCount: number;
  likesCount: number;
  readsCount: number;
  bookmarksCount: number;
}

export interface User {
  id: string;
  name: string;
  email: string;
  avatar: string;
  bio: string;
  followersCount: number;
  joinedDate: number;
  publicBookshelf?: boolean;
  isAdmin?: boolean;
}

export type QuoteCategory = 
  | 'Inspirational' 
  | 'Romantic' 
  | 'Philosophical' 
  | 'Motivational' 
  | 'Friendship' 
  | 'Literary';

export interface Quote {
  id: string;
  text: string;
  author: string;
  category: QuoteCategory;
  isOriginal: boolean;
  source?: string;
}

export interface DailyQuote {
  date: string;
  text: string;
  style: string;
  attribution: 'Generated by INOKORA' | 'Original quote';
  isAiGenerated: boolean;
}

export type BookshelfStatus = 'reading' | 'completed' | 'want_to_read';

export interface BookshelfItem {
  storyId: string;
  status: BookshelfStatus;
  addedAt: number;
  isPrivate: boolean;
}

export interface ReadingProgress {
  storyId: string;
  currentChapterId: string;
  currentChapterIndex: number;
  percent: number;
  lastReadAt: number;
  scrollY?: number;
}

export interface StoryComment {
  id: string;
  storyId: string;
  chapterId?: string;
  chapterTitle?: string;
  userId: string;
  authorName: string;
  avatar?: string;
  text: string;
  createdAt: number;
}

export interface StoryReport {
  id: string;
  storyId: string;
  storyTitle: string;
  reporterEmail: string;
  reason: string;
  details?: string;
  status: 'pending' | 'resolved';
  createdAt: number;
}
